#!/usr/bin/env bash
#
# Generates the SPIR-V permutation headers for the FidelityFX Vulkan backend.
#
# This reproduces, outside of CMake, exactly what
#   sdk/include/FidelityFX/gpu/CMakeCompileShaders.txt
# (function compile_shaders_with_depfile) does for the VK backend:
# every shader is compiled 4 times (wave32 / wave64 / wave32-16bit /
# wave64-16bit) and each run emits
#   <name>[_wave64][_16bit]_permutations.h  (+ <name>_<hash>.h blob headers)
#
# On the VK/GLSL path the HLSL-only wave size arguments are empty, so the four
# runs differ only in "-name=<name><suffix>" and "-DFFX_HALF=<0|1>".
#
# Usage: ./gen_shaders.sh [component ...]
#        components: fsr3upscaler frameinterpolation opticalflow fsr2
#        (default: all of them)
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SDK_DIR="${FFX_SDK_ROOT:-$SCRIPT_DIR/ffx-sdk-1.1.4}/sdk"

OUT_DIR="$SCRIPT_DIR/generated"
export WINEPREFIX="${WINEPREFIX:-$SCRIPT_DIR/wineprefix}"
export WINEDEBUG="${WINEDEBUG:--all}"

SC_EXE="$SDK_DIR/tools/binary_store/FidelityFX_SC.exe"
TOOL_DIR="$(dirname "$SC_EXE")"
# Shader sources come from the patched copy (./src, see prepare_sources.sh).
PATCHED_SDK="$SCRIPT_DIR/src/sdk"
GPU_PATH="$PATCHED_SDK/include/FidelityFX/gpu"
SHADER_ROOT="$PATCHED_SDK/src/backends/vk/shaders"

[ -f "$SC_EXE" ] || { echo "error: $SC_EXE not found" >&2; exit 1; }

mkdir -p "$OUT_DIR"
# FidelityFX_SC.exe is a Windows binary: hand it Windows paths.
OUT_WIN="$(winepath -w "$OUT_DIR")"

# Arguments shared by every Vulkan shader compilation
# (CMakeShaders<Component>.txt: <COMPONENT>_API_BASE_ARGS).
API_ARGS=(
    -compiler=glslang
    -e CS
    --target-env vulkan1.2
    -S comp
    -Os
    -DFFX_GLSL=1
)

# compile_shader <shader.glsl> <include dirs...>
# Uses the global COMPONENT_ARGS array as the per-component base/permutation args.
compile_shader() {
    local shader_unix="$1"
    shift
    local includes=("$@")

    local base
    base="$(basename "$shader_unix" .glsl)"
    local shader_win
    shader_win="$(winepath -w "$shader_unix")"

    echo "=== $base"
    # <FFX_HALF>|<name suffix> -- the four variants generated by
    # compile_shaders_with_depfile for the VK backend.
    local variant half suffix
    for variant in "0|" "0|_wave64" "1|_16bit" "1|_wave64_16bit"; do
        half="${variant%%|*}"
        suffix="${variant#*|}"
        ( cd "$TOOL_DIR" && wine "$SC_EXE" \
              "${COMPONENT_ARGS[@]}" \
              "${API_ARGS[@]}" \
              -name="${base}${suffix}" \
              "-DFFX_HALF=${half}" \
              "${includes[@]}" \
              -output="$OUT_WIN" \
              "$shader_win" )
    done
}

gen_fsr3upscaler() {
    # CMakeCompileFSR3UpscalerShaders.txt
    COMPONENT_ARGS=(
        -reflection -deps=gcc -DFFX_GPU=1
        -DFFX_FSR3UPSCALER_OPTION_UPSAMPLE_SAMPLERS_USE_DATA_HALF=0
        -DFFX_FSR3UPSCALER_OPTION_ACCUMULATE_SAMPLERS_USE_DATA_HALF=0
        -DFFX_FSR3UPSCALER_OPTION_REPROJECT_SAMPLERS_USE_DATA_HALF=1
        -DFFX_FSR3UPSCALER_OPTION_POSTPROCESSLOCKSTATUS_SAMPLERS_USE_DATA_HALF=0
        -DFFX_FSR3UPSCALER_OPTION_UPSAMPLE_USE_LANCZOS_TYPE=2
        "-DFFX_FSR3UPSCALER_OPTION_REPROJECT_USE_LANCZOS_TYPE={0,1}"
        "-DFFX_FSR3UPSCALER_OPTION_HDR_COLOR_INPUT={0,1}"
        "-DFFX_FSR3UPSCALER_OPTION_LOW_RESOLUTION_MOTION_VECTORS={0,1}"
        "-DFFX_FSR3UPSCALER_OPTION_JITTERED_MOTION_VECTORS={0,1}"
        "-DFFX_FSR3UPSCALER_OPTION_INVERTED_DEPTH={0,1}"
        "-DFFX_FSR3UPSCALER_OPTION_APPLY_SHARPENING={0,1}"
    )
    local includes=(-I"$GPU_PATH" -I"$GPU_PATH/fsr3upscaler")
    local f
    for f in "$SHADER_ROOT"/fsr3upscaler/*.glsl; do
        compile_shader "$f" "${includes[@]}"
    done
}

gen_frameinterpolation() {
    # CMakeCompileFrameinterpolationShaders.txt
    COMPONENT_ARGS=(
        -DFFX_FRAMEINTERPOLATION_OPTION_UPSAMPLE_SAMPLERS_USE_DATA_HALF=0
        -DFFX_FRAMEINTERPOLATION_OPTION_ACCUMULATE_SAMPLERS_USE_DATA_HALF=0
        -DFFX_FRAMEINTERPOLATION_OPTION_REPROJECT_SAMPLERS_USE_DATA_HALF=1
        -DFFX_FRAMEINTERPOLATION_OPTION_POSTPROCESSLOCKSTATUS_SAMPLERS_USE_DATA_HALF=0
        -DFFX_FRAMEINTERPOLATION_OPTION_UPSAMPLE_USE_LANCZOS_TYPE=2
        -reflection -deps=gcc -DFFX_GPU=1
        "-DFFX_FRAMEINTERPOLATION_OPTION_LOW_RES_MOTION_VECTORS={0,1}"
        "-DFFX_FRAMEINTERPOLATION_OPTION_JITTER_MOTION_VECTORS={0,1}"
        "-DFFX_FRAMEINTERPOLATION_OPTION_INVERTED_DEPTH={0,1}"
    )
    local includes=(-I"$GPU_PATH" -I"$GPU_PATH/frameinterpolation")
    local f
    for f in "$SHADER_ROOT"/frameinterpolation/*.glsl; do
        compile_shader "$f" "${includes[@]}"
    done
}

gen_opticalflow() {
    # CMakeCompileOpticalflowShaders.txt
    COMPONENT_ARGS=(
        -reflection -deps=gcc -DFFX_GPU=1
        "-DFFX_OPTICALFLOW_OPTION_HDR_COLOR_INPUT={0,1}"
    )
    local includes=(-I"$GPU_PATH" -I"$GPU_PATH/opticalflow")
    local f
    for f in "$SHADER_ROOT"/opticalflow/*.glsl; do
        compile_shader "$f" "${includes[@]}"
    done
}

gen_fsr2() {
    # CMakeCompileFSR2Shaders.txt (the ffx-api FSR2 provider is part of the
    # same shared library, so its blobs are needed as well)
    COMPONENT_ARGS=(
        -reflection -deps=gcc -DFFX_GPU=1
        -DFFX_FSR2_OPTION_UPSAMPLE_SAMPLERS_USE_DATA_HALF=0
        -DFFX_FSR2_OPTION_ACCUMULATE_SAMPLERS_USE_DATA_HALF=0
        -DFFX_FSR2_OPTION_REPROJECT_SAMPLERS_USE_DATA_HALF=1
        -DFFX_FSR2_OPTION_POSTPROCESSLOCKSTATUS_SAMPLERS_USE_DATA_HALF=0
        -DFFX_FSR2_OPTION_UPSAMPLE_USE_LANCZOS_TYPE=2
        "-DFFX_FSR2_OPTION_REPROJECT_USE_LANCZOS_TYPE={0,1}"
        "-DFFX_FSR2_OPTION_HDR_COLOR_INPUT={0,1}"
        "-DFFX_FSR2_OPTION_LOW_RESOLUTION_MOTION_VECTORS={0,1}"
        "-DFFX_FSR2_OPTION_JITTERED_MOTION_VECTORS={0,1}"
        "-DFFX_FSR2_OPTION_INVERTED_DEPTH={0,1}"
        "-DFFX_FSR2_OPTION_APPLY_SHARPENING={0,1}"
    )
    local includes=(-I"$GPU_PATH" -I"$GPU_PATH/fsr2")
    local f
    for f in "$SHADER_ROOT"/fsr2/*.glsl; do
        compile_shader "$f" "${includes[@]}"
    done
}

components=("$@")
if [ ${#components[@]} -eq 0 ]; then
    components=(fsr3upscaler frameinterpolation opticalflow fsr2)
fi

for c in "${components[@]}"; do
    case "$c" in
        fsr3upscaler)      gen_fsr3upscaler ;;
        frameinterpolation) gen_frameinterpolation ;;
        opticalflow)       gen_opticalflow ;;
        fsr2)              gen_fsr2 ;;
        *) echo "error: unknown component '$c'" >&2; exit 1 ;;
    esac
done

echo
echo "done: $(find "$OUT_DIR" -name '*_permutations.h' | wc -l) permutation headers in $OUT_DIR"
