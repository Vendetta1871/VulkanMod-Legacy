package net.vesu.shader;

import net.vesu.Env;

import com.google.gson.JsonObject;
import com.google.gson.JsonParseException;
import com.google.gson.JsonParser;
import net.vesu.Initializer;
import net.vesu.pack.PackKind;
import net.vesu.pack.ir.IrPack;
import net.vesu.pack.optifine.OptiFineFrontend;
import net.vesu.pack.postfx.PostEffectFrontend;
import net.vesu.pack.source.PackSource;

import java.io.IOException;
import java.nio.file.DirectoryStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;

/**
 * The shader packs in {@code shaderpacks/} and the selected one (docs/shaderpacks, M0).
 *
 * <p>Packs are folders or zips, plus the built-in packs shipped in the jar
 * ({@code builtin:<name>}, under {@code /assets/vesu/shaderpacks/}). Each is detected
 * by its marker files ({@link PackKind}); usable formats are parsed in full, so the list can
 * show their errors. Other formats are listed but not usable until their frontend exists.
 * The selection is the config's {@code shaderPack}; {@code VESU_SHADERPACK=<id>}
 * overrides it for one run without saving (autotests). {@code PackRuntime} renders the
 * active pack and reports build errors back here.</p>
 */
public final class PackManager {

    public static final Path DIR = Paths.get("shaderpacks");

    /** Id prefix of the packs shipped in the mod jar. */
    public static final String BUILTIN_PREFIX = "builtin:";
    private static final String BUILTIN_ROOT = "assets/vesu/shaderpacks/";
    private static final List<String> BUILTIN = List.of("sample_post", "vibrant_visuals");
    private static final Map<String, String> BUILTIN_NAMES = Map.of(
            "sample_post", "Sample Post (built-in)",
            "vibrant_visuals", "Vibrant Visuals (built-in)");

    /** Debug override of the selection, not saved (autotests). */
    private static final String ENV_PACK = Env.get("VESU_SHADERPACK");

    /** Debug choice of a manifest's profile, until options have a GUI (M5). */
    private static final String ENV_PROFILE = Env.get("VESU_PACK_PROFILE");
    /** Debug override of option values: {@code NAME=VALUE,NAME=VALUE}. */
    private static final String ENV_OPTIONS = Env.get("VESU_PACK_OPTIONS");

    /**
     * One listed pack. {@code usable}: its format has a frontend and it parsed without error.
     * {@code iris}: an OptiFine-format pack that uses Iris features.
     */
    public record Entry(String id, String name, PackKind kind, boolean usable, String message, boolean iris) {
        Entry(String id, String name, PackKind kind, boolean usable, String message) {
            this(id, name, kind, usable, message, false);
        }

        /** The format as shown in the list: Iris for an OptiFine-format pack that needs Iris. */
        public String format() {
            return iris ? "Iris" : kind.label;
        }
    }

    private static List<Entry> entries = List.of();
    private static IrPack active;
    /** Programs generated by the active pack's frontend, read like pack files. */
    private static Map<String, String> activePrograms = Map.of();
    private static String activeError;
    private static OptiFineFrontend.Result activeOptions;

    private PackManager() {
    }

    /** Loads the configured pack, if any. Called once after the config. */
    public static void init() {
        try {
            Files.createDirectories(DIR);
        } catch (IOException e) {
            Initializer.LOGGER.warn("[shaderpacks] cannot create {}: {}", DIR.toAbsolutePath(), e.toString());
        }
        loadSelected();
    }

    /** Re-reads the folder. Called when the pack screen opens. */
    public static synchronized void rescan() {
        List<Entry> found = new ArrayList<>();
        for (String name : BUILTIN) {
            found.add(describeSource(BUILTIN_PREFIX + name));
        }
        if (Files.isDirectory(DIR)) {
            try (DirectoryStream<Path> stream = Files.newDirectoryStream(DIR)) {
                for (Path p : stream) {
                    String file = p.getFileName().toString().toLowerCase();
                    boolean zip = file.endsWith(".zip") || file.endsWith(".mcpack");
                    if (Files.isDirectory(p) || (zip && Files.isRegularFile(p))) {
                        found.add(describe(p));
                    }
                }
            } catch (IOException e) {
                Initializer.LOGGER.warn("[shaderpacks] cannot list {}: {}", DIR.toAbsolutePath(), e.toString());
            }
        }
        found.sort((a, b) -> a.name().compareToIgnoreCase(b.name()));
        entries = Collections.unmodifiableList(found);
    }

    public static List<Entry> entries() {
        return entries;
    }

    /** The parsed selected pack, or null (none selected, or it failed to load). */
    public static IrPack active() {
        return active;
    }

    /**
     * RT and a pack with its own lighting exclude each other: such a pack is paused while RT
     * is on. Only a post-only pack ({@code renderer.rt}) runs over the composited image.
     */
    public static boolean pausedByRt(IrPack pack) {
        return pack != null && net.vesu.vulkan.rt.RtScene.enabled()
                && !(pack.renderer.has("rt") && pack.renderer.get("rt").getAsBoolean());
    }

    /** A pack's {@code key=false} from shaders.properties, kept in {@code renderer}. */
    public static boolean rendererIsFalse(String key) {
        IrPack pack = active;
        return pack != null && pack.renderer.has(key) && pack.renderer.get(key).getAsString().equals("false");
    }

    /** {@code clouds=off} in shaders.properties. */
    public static boolean cloudsOff() {
        IrPack pack = active;
        return pack != null && pack.renderer.has("clouds") && pack.renderer.get("clouds").getAsString().equals("off");
    }

    public static boolean rendererIsTrue(String key) {
        IrPack pack = active;
        return pack != null && pack.renderer.has(key) && pack.renderer.get(key).getAsString().equals("true");
    }

    /** Why the selected pack is not active, or null. */
    public static String activeError() {
        return activeError;
    }

    public static String selectedId() {
        return ENV_PACK != null ? (ENV_PACK.isEmpty() || ENV_PACK.equals("off") ? null : ENV_PACK)
                : Initializer.CONFIG.shaderPack;
    }

    /** Opens the active pack's files again (the runtime compiles its programs); the caller closes it. */
    public static PackSource openActive() throws IOException {
        if (active == null) throw new IOException("no active pack");
        return PackSource.overlay(open(selectedId()), activePrograms);
    }

    /** The runtime could not build the active pack: shown as its error, and the pack stays off. */
    public static synchronized void reportRuntimeError(String message) {
        activeError = message;
        active = null;
    }

    private static boolean loadedWithLod;

    /** Turning LODs on or off changes what an OptiFine pack compiles (DISTANT_HORIZONS): load it again. */
    public static synchronized void lodChanged() {
        if (activeOptions != null && loadedWithLod != net.vesu.lod.mc.LodSystem.enabled()) loadSelected();
    }

    /** Selects a pack by id (null = none), loads it and saves the config. */
    public static synchronized void select(String id) {
        Initializer.CONFIG.shaderPack = id;
        loadSelected();
        Initializer.saveConfig();
    }

    private static void loadSelected() {
        active = null;
        activePrograms = Map.of();
        activeError = null;
        activeOptions = null;
        PackIds.load(null);
        PbrAtlases.overrides.clear();
        BedrockMaterials.clearColors();
        PbrAtlases.markDirty();
        String id = selectedId();
        if (id == null) {
            return;
        }
        try (PackSource src = open(id)) {
            PackKind kind = PackKind.detect(src);
            if (kind == PackKind.POST_EFFECT) {
                PostEffectFrontend.Result lowered = lowerPostEffect(src, id);
                for (String w : lowered.warnings()) Initializer.LOGGER.warn("[shaderpacks] {}: {}", id, w);
                activePrograms = lowered.programs();
                active = lowered.pack();
                Initializer.LOGGER.info("[shaderpacks] loaded {} ({}): {} scene variant(s), {} program(s)",
                        active.name, id, active.scenes.size(), activePrograms.size());
            } else if (kind == PackKind.OPTIFINE) {
                OptiFineFrontend.Result lowered = lowerOptiFine(src, id);
                new java.util.TreeSet<>(lowered.warnings()).forEach(w -> Initializer.LOGGER.warn("[shaderpacks] {}: {}", id, w));
                activePrograms = lowered.programs();
                activeOptions = lowered;
                active = lowered.pack();
                PackIds.load(active);
                Initializer.LOGGER.info("[shaderpacks] loaded {} ({}): {} program(s), {} option(s)",
                        active.name, id, activePrograms.size(), lowered.options().size());
            } else if (kind == PackKind.BEDROCK) {
                net.vesu.pack.bedrock.BedrockFrontend.Result lowered = net.vesu.pack.bedrock.BedrockFrontend.lower(src, id);
                for (String w : lowered.warnings()) Initializer.LOGGER.warn("[shaderpacks] {}: {}", id, w);
                activePrograms = lowered.programs();
                BedrockMaterials.load(src);
                active = lowered.pack();
                PackIds.load(active);
                Initializer.LOGGER.info("[shaderpacks] loaded {} ({})", active.name, id);
            } else if (kind != PackKind.NATIVE) {
                activeError = kind.label + " packs are not supported yet";
            } else {
                active = parseNative(src, id);
                Initializer.LOGGER.info("[shaderpacks] loaded {} ({}): {} texture(s), {} stage(s)",
                        active.name, id, active.textures.size(), active.commandLists.size());
            }
        } catch (IOException | RuntimeException e) {
            activeError = message(e);
        }
        if (activeError != null) {
            Initializer.LOGGER.warn("[shaderpacks] {}: {}", id, activeError);
        }
    }

    private static String builtinName(String id) {
        return id.startsWith(BUILTIN_PREFIX) ? id.substring(BUILTIN_PREFIX.length()) : "";
    }

    /**
     * Iris extensions in shaders.properties: declared {@code iris.features}, custom images or
     * shader storage buffers. Such a pack is written for Iris and is labelled so.
     */
    private static boolean usesIris(PackSource src) {
        try {
            if (!src.exists("shaders/shaders.properties")) return false;
            return java.util.regex.Pattern.compile("(?m)^\\s*(iris\\.features\\.|image\\.|bufferObject\\.)")
                    .matcher(src.read("shaders/shaders.properties")).find();
        } catch (IOException e) {
            return false;
        }
    }

    private static Entry describe(Path p) {
        return describeSource(p.getFileName().toString());
    }

    private static Entry describeSource(String id) {
        try (PackSource src = open(id)) {
            PackKind kind = PackKind.detect(src);
            if (kind == PackKind.POST_EFFECT) {
                try {
                    return new Entry(id, lowerPostEffect(src, id).pack().name, kind, true, null);
                } catch (IllegalArgumentException e) {
                    return new Entry(id, id, kind, false, message(e));
                }
            }
            if (kind == PackKind.OPTIFINE || kind == PackKind.BEDROCK) {
                String name = BUILTIN_NAMES.getOrDefault(builtinName(id), id.replaceAll("\\.(zip|mcpack)$", ""));
                return new Entry(id, name, kind, true, null, kind == PackKind.OPTIFINE && usesIris(src));
            }
            if (kind != PackKind.NATIVE) {
                String msg = kind == PackKind.UNKNOWN ? "not a shader pack" : kind.label + " packs are not supported yet";
                return new Entry(id, src.id(), kind, false, msg);
            }
            IrPack pack = parseNative(src, id);
            return new Entry(id, BUILTIN_NAMES.getOrDefault(builtinName(id), pack.name), kind, true,
                    pack.version.isEmpty() ? null : "v" + pack.version);
        } catch (IOException | RuntimeException e) {
            return new Entry(id, id, PackKind.NATIVE, false, message(e));
        }
    }

    /** Opens a pack by id: {@code builtin:<name>} from the jar, else a folder or zip in {@link #DIR}. */
    private static PackSource open(String id) throws IOException {
        if (id.startsWith(BUILTIN_PREFIX)) {
            String name = id.substring(BUILTIN_PREFIX.length());
            if (!BUILTIN.contains(name)) throw new IOException("pack not found: " + id);
            return PackSource.classpath(PackManager.class.getClassLoader(), BUILTIN_ROOT + name, id);
        }
        Path p = DIR.resolve(id).normalize();
        if (!p.startsWith(DIR) || !Files.exists(p)) {
            throw new IOException("pack not found: " + id);
        }
        return Files.isDirectory(p) ? PackSource.directory(p) : PackSource.zip(p);
    }

    /** The OptiFine way: {@code shaderpacks/<pack>.txt} holds the options that differ from the defaults. */
    private static Map<String, String> readOptions(String id) {
        Map<String, String> values = new java.util.TreeMap<>();
        Path file = DIR.resolve(id + ".txt");
        if (Files.isRegularFile(file)) {
            try {
                for (String line : Files.readAllLines(file)) {
                    int eq = line.indexOf('=');
                    if (eq > 0 && !line.startsWith("#")) values.put(line.substring(0, eq).trim(), line.substring(eq + 1).trim());
                }
            } catch (IOException e) {
                Initializer.LOGGER.warn("[shaderpacks] cannot read {}: {}", file, e.toString());
            }
        }
        if (ENV_OPTIONS != null) {
            for (String kv : ENV_OPTIONS.split(",")) {
                int eq = kv.indexOf('=');
                if (eq > 0) values.put(kv.substring(0, eq), kv.substring(eq + 1));
            }
        }
        return values;
    }

    /** Saves the options and reloads the pack; the runtime rebuilds on the next frame. */
    public static synchronized void applyOptions(Map<String, String> values) {
        String id = selectedId();
        if (id == null) return;
        try {
            List<String> lines = new ArrayList<>();
            values.forEach((k, v) -> lines.add(k + "=" + v));
            Files.write(DIR.resolve(id + ".txt"), lines);
        } catch (IOException e) {
            Initializer.LOGGER.warn("[shaderpacks] cannot save options: {}", e.toString());
        }
        loadSelected();
    }

    /** The active OptiFine pack's options and pages, or null. */
    public static OptiFineFrontend.Result activeOptions() {
        return activeOptions;
    }

    /** {@code MC_GL_VENDOR_*} and {@code MC_GL_RENDERER_*}, from the Vulkan device instead of GL strings. */
    private static void deviceMacros(String vendor, String device, Map<String, String> macros) {
        String d = device.toLowerCase();
        if (vendor.equals("4318")) {
            macros.put("MC_GL_VENDOR_NVIDIA", "");
            macros.put(d.contains("quadro") ? "MC_GL_RENDERER_QUADRO" : "MC_GL_RENDERER_GEFORCE", "");
        } else if (vendor.equals("4098")) {
            macros.put("MC_GL_VENDOR_ATI", "");
            macros.put("MC_GL_VENDOR_AMD", "");
            macros.put("MC_GL_RENDERER_RADEON", "");
        } else if (vendor.equals("32902")) {
            macros.put("MC_GL_VENDOR_INTEL", "");
            macros.put("MC_GL_RENDERER_INTEL", "");
        } else {
            macros.put("MC_GL_VENDOR_OTHER", "");
            macros.put("MC_GL_RENDERER_OTHER", "");
        }
    }

    private static OptiFineFrontend.Result lowerOptiFine(PackSource src, String id) throws IOException {
        Map<String, String> macros = new java.util.HashMap<>();
        String os = System.getProperty("os.name", "").toLowerCase();
        macros.put(os.contains("win") ? "MC_OS_WINDOWS" : os.contains("mac") ? "MC_OS_MAC" : "MC_OS_LINUX", "");
        var device = net.vesu.vulkan.Vulkan.getDeviceInfo();
        if (device != null) deviceMacros(device.vendorId, device.deviceName, macros);
        // Distant terrain through the pack's own DH programs (AUDIT 5.16, contract B).
        loadedWithLod = net.vesu.lod.mc.LodSystem.enabled();
        if (loadedWithLod) macros.put("DISTANT_HORIZONS", "");
        return OptiFineFrontend.lower(src, id, readOptions(id), macros);
    }

    private static PostEffectFrontend.Result lowerPostEffect(PackSource src, String id) throws IOException {
        return PostEffectFrontend.lower(src, id, ENV_PROFILE);
    }

    /** Parses pack.json and checks that every program file it names exists. */
    private static IrPack parseNative(PackSource src, String id) throws IOException {
        JsonObject root;
        try {
            root = JsonParser.parseString(src.read("pack.json")).getAsJsonObject();
        } catch (JsonParseException | IllegalStateException e) {
            throw new IllegalArgumentException("pack.json is not a JSON object: " + e.getMessage());
        }
        IrPack pack = IrPack.parse(id, root);
        checkPrograms(src, pack);
        for (IrPack variant : pack.scenes.values()) checkPrograms(src, variant);
        return pack;
    }

    private static void checkPrograms(PackSource src, IrPack pack) {
        if (pack.combination == null) {
            throw new IllegalArgumentException("pack has no combination pass");
        }
        for (List<IrPack.Pass> passes : pack.commandLists.values()) {
            for (IrPack.Pass pass : passes) {
                requirePrograms(src, pass);
            }
        }
        requirePrograms(src, pack.combination);
    }

    private static void requirePrograms(PackSource src, IrPack.Pass pass) {
        for (String program : new String[]{pass.vertex, pass.fragment, pass.compute}) {
            if (program != null && !src.exists(program)) {
                throw new IllegalArgumentException("pass " + pass.name + ": missing program " + program);
            }
        }
    }

    private static String message(Exception e) {
        String m = e.getMessage();
        return m == null ? e.getClass().getSimpleName() : m;
    }
}
