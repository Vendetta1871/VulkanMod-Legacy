package net.vesu.weather;

import net.minecraft.client.Minecraft;
import net.minecraft.client.renderer.texture.TextureAtlasSprite;
import net.minecraft.client.renderer.texture.TextureMap;
import net.minecraft.client.resources.IResource;
import net.minecraft.client.resources.IResourceManager;
import net.minecraft.util.ResourceLocation;
import net.minecraftforge.client.event.TextureStitchEvent;
import net.minecraftforge.common.MinecraftForge;
import net.minecraftforge.fml.common.eventhandler.SubscribeEvent;
import net.vesu.Initializer;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Random;
import java.util.function.Function;

/**
 * The weather sprites, generated into the block atlas when it is stitched: rain and snow cut from
 * vanilla's rain.png / snow.png (16 single sprites and 4 merged "heavy" ones each), ripple rings,
 * the wall streak, and the fog / dust-haze sheets.
 */
public final class WeatherSprites {

    private static final Map<String, TextureAtlasSprite> SPRITES = new HashMap<>();
    private static final Map<WeatherDef, TextureAtlasSprite[]> RESOLVED = new HashMap<>();
    private static final int RIPPLE_RES = 16;

    private WeatherSprites() {}

    public static void init() {
        MinecraftForge.EVENT_BUS.register(WeatherSprites.class);
    }

    @SubscribeEvent
    public static void onStitch(TextureStitchEvent.Pre event) {
        TextureMap map = event.getMap();
        if (map != Minecraft.getMinecraft().getTextureMapBlocks()) return;
        SPRITES.clear();
        RESOLVED.clear();
        SHEETS.clear();
        for (int i = 0; i < 16; i++) {
            final int k = i;
            add(map, "rain_" + i, m -> single(sheet(m, "rain", true), k));
            add(map, "snow_" + i, m -> single(sheet(m, "snow", false), k));
        }
        for (int i = 0; i < 4; i++) {
            final int k = i;
            add(map, "heavy_rain_" + i, m -> heavy(sheet(m, "rain", true), k));
            add(map, "heavy_snow_" + i, m -> heavy(sheet(m, "snow", false), k));
        }
        for (int i = 0; i < 8; i++) {
            final int k = i;
            add(map, "ripple_" + i, m -> ripple(k));
        }
        add(map, "streak", m -> streak());
        add(map, "fog_translucent", m -> fogTranslucent());
        add(map, "horizontal_fog", m -> horizontalFog());
        add(map, "fog_dithered", m -> fogDithered());
    }

    static TextureAtlasSprite get(String name) {
        return SPRITES.get(name);
    }

    static TextureAtlasSprite[] resolve(WeatherDef def) {
        return RESOLVED.computeIfAbsent(def, d -> {
            List<TextureAtlasSprite> out = new ArrayList<>();
            for (String n : d.sprites) {
                TextureAtlasSprite s = SPRITES.get(n);
                if (s != null) out.add(s);
            }
            return out.toArray(new TextureAtlasSprite[0]);
        });
    }

    static TextureAtlasSprite deadBush() {
        return Minecraft.getMinecraft().getTextureMapBlocks().getAtlasSprite("minecraft:blocks/deadbush");
    }

    private static void add(TextureMap map, String name, Function<IResourceManager, int[][]> generator) {
        Generated sprite = new Generated("vesu:weather/" + name, generator);
        if (map.setTextureEntry(sprite)) SPRITES.put(name, sprite);
    }

    /** A sprite whose pixels are produced in code; result[0] = {width, height}, result[1] = ARGB pixels. */
    private static final class Generated extends TextureAtlasSprite {
        private final Function<IResourceManager, int[][]> generator;

        Generated(String name, Function<IResourceManager, int[][]> generator) {
            super(name);
            this.generator = generator;
        }

        @Override
        public boolean hasCustomLoader(IResourceManager manager, ResourceLocation location) {
            return true;
        }

        @Override
        public boolean load(IResourceManager manager, ResourceLocation location,
                            Function<ResourceLocation, TextureAtlasSprite> textureGetter) {
            try {
                int[][] r = generator.apply(manager);
                width = r[0][0];
                height = r[0][1];
                List<int[][]> frames = new ArrayList<>();
                // One slot per mip level, like vanilla sprite loading: level 0 filled, the rest
                // generated by the atlas (a shorter array overruns in generateMipmapData).
                int[][] levels = new int[17][];
                levels[0] = r[1];
                frames.add(levels);
                setFramesTextureData(frames);
                return false;
            } catch (Exception e) {
                Initializer.LOGGER.error("[weather] cannot build sprite {}", getIconName(), e);
                return true;
            }
        }
    }

    // --- rain and snow --------------------------------------------------------------------------

    private static final Map<String, BufferedImage> SHEETS = new HashMap<>();

    /** Vanilla's rain.png / snow.png; the rain desaturated (each pixel's RGB → its max channel) for the water tint. */
    private static BufferedImage sheet(IResourceManager manager, String name, boolean desaturate) {
        return SHEETS.computeIfAbsent(name, n -> {
            try (IResource res = manager.getResource(new ResourceLocation("textures/environment/" + n + ".png"));
                 InputStream in = res.getInputStream()) {
                BufferedImage img = ImageIO.read(in);
                BufferedImage out = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_ARGB);
                int maxA = 0;
                for (int y = 0; y < img.getHeight(); y++) {
                    for (int x = 0; x < img.getWidth(); x++) maxA = Math.max(maxA, img.getRGB(x, y) >>> 24);
                }
                int boost = maxA == 0 || maxA == 255 ? 1 : 255 / maxA;
                for (int y = 0; y < img.getHeight(); y++) {
                    for (int x = 0; x < img.getWidth(); x++) {
                        int p = img.getRGB(x, y);
                        int a = Math.min(255, (p >>> 24) * boost);
                        int r = p >> 16 & 255, g = p >> 8 & 255, b = p & 255;
                        if (desaturate) {
                            int m = Math.max(r, Math.max(g, b));
                            r = g = b = m;
                        }
                        out.setRGB(x, y, a << 24 | r << 16 | g << 8 | b);
                    }
                }
                return out;
            } catch (Exception e) {
                throw new RuntimeException(e);
            }
        });
    }

    /** Sprite i of the 2-column sheet (column i / rows, row i % rows), rotated 180°. */
    private static int[] cut(BufferedImage sheet, int i, int size) {
        int rows = sheet.getHeight() / size;
        int col = i / rows, row = i % rows;
        int[] px = new int[size * size];
        for (int y = 0; y < size; y++) {
            for (int x = 0; x < size; x++) {
                px[(size - 1 - y) * size + (size - 1 - x)] = sheet.getRGB(col * size + x, row * size + y);
            }
        }
        return px;
    }

    private static int[][] single(BufferedImage sheet, int i) {
        int size = sheet.getWidth() / 2;
        return new int[][]{{size, size}, cut(sheet, i, size)};
    }

    /** Sprites 4k..4k+3 merged, keeping the more opaque pixel. */
    private static int[][] heavy(BufferedImage sheet, int k) {
        int size = sheet.getWidth() / 2;
        int[] out = new int[size * size];
        for (int j = 0; j < 4; j++) {
            int[] px = cut(sheet, 4 * k + j, size);
            for (int p = 0; p < out.length; p++) {
                if ((px[p] >>> 24) > (out[p] >>> 24)) out[p] = px[p];
            }
        }
        return new int[][]{{size, size}, out};
    }

    // --- ripple rings ---------------------------------------------------------------------------

    private static int[][] ripple(int i) {
        int n = RIPPLE_RES;
        int[] px = new int[n * n];
        int radius = Math.max(1, Math.min(n / 2 - 1, (n / 2) / 8 * (i + 1)));
        int cx = n / 2, cy = n / 2;
        // Midpoint circle, 8-way symmetric, one pixel wide.
        int x = radius, y = 0, err = 1 - radius;
        while (x >= y) {
            int[][] pts = {{x, y}, {y, x}, {-y, x}, {-x, y}, {-x, -y}, {-y, -x}, {y, -x}, {x, -y}};
            for (int[] p : pts) {
                int px0 = cx + p[0], py0 = cy + p[1];
                if (px0 >= 0 && px0 < n && py0 >= 0 && py0 < n) px[py0 * n + px0] = 0xFFFFFFFF;
            }
            y++;
            if (err < 0) {
                err += 2 * y + 1;
            } else {
                x--;
                err += 2 * (y - x) + 1;
            }
        }
        return new int[][]{{n, n}, px};
    }

    // --- streak and fog sheets ------------------------------------------------------------------

    /** A one-pixel vertical trickle, grey 217, fading in from the top. */
    private static int[][] streak() {
        int[] px = new int[16 * 16];
        int[] alpha = {10, 18, 27, 37, 50, 63, 77, 92, 107, 122, 136, 149, 162, 174, 186, 197};
        for (int y = 0; y < 16; y++) px[y * 16 + 7] = alpha[y] << 24 | 217 << 16 | 217 << 8 | 217;
        return new int[][]{{16, 16}, px};
    }

    /** Smooth value noise in [0, 1] on a periodic lattice. */
    private static float noise(Random seed, float[] lattice, int period, float x, float y) {
        int x0 = (int) Math.floor(x), y0 = (int) Math.floor(y);
        float fx = x - x0, fy = y - y0;
        fx = fx * fx * (3 - 2 * fx);
        fy = fy * fy * (3 - 2 * fy);
        float a = lattice[Math.floorMod(y0, period) * period + Math.floorMod(x0, period)];
        float b = lattice[Math.floorMod(y0, period) * period + Math.floorMod(x0 + 1, period)];
        float c = lattice[Math.floorMod(y0 + 1, period) * period + Math.floorMod(x0, period)];
        float d = lattice[Math.floorMod(y0 + 1, period) * period + Math.floorMod(x0 + 1, period)];
        return a + (b - a) * fx + (c - a) * fy + (a - b - c + d) * fx * fy;
    }

    private static float[] lattice(Random r, int period) {
        float[] l = new float[period * period];
        for (int i = 0; i < l.length; i++) l[i] = r.nextFloat();
        return l;
    }

    /** Fractal blotches, about 0..1. */
    private static float fbm(Random r, float[][] lattices, float x, float y) {
        float sum = 0, amp = 0.5f, norm = 0;
        for (int o = 0; o < lattices.length; o++) {
            int period = 4 << o;
            sum += amp * noise(r, lattices[o], period, x * period, y * period);
            norm += amp;
            amp *= 0.5f;
        }
        return sum / norm;
    }

    /** A soft cloudy wisp: grey ~200-250, alpha up to ~100, a horizontally gaussian band over the full height. */
    private static int[][] fogTranslucent() {
        Random r = new Random(0x57A71);
        float[][] lat = {lattice(r, 4), lattice(r, 8), lattice(r, 16), lattice(r, 32)};
        int n = 64;
        int[] px = new int[n * n];
        for (int y = 0; y < n; y++) {
            float vy = (y + 0.5f) / n;
            float vertical = smooth(0.0f, 0.12f, vy) * (1.0f - 0.55f * smooth(0.6f, 1.0f, vy));
            for (int x = 0; x < n; x++) {
                float dx = (x + 0.5f - 31.0f) / 8.0f;
                float band = (float) Math.exp(-0.5 * dx * dx);
                float f = fbm(r, lat, x / (float) n, y / (float) n);
                float a = band * vertical * clamp((f - 0.25f) * 1.9f, 0, 1) * 101.0f / 0.75f;
                int grey = (int) (198 + 53 * f);
                px[y * n + x] = (int) clamp(a, 0, 101) << 24 | grey << 16 | grey << 8 | grey;
            }
        }
        return new int[][]{{n, n}, px};
    }

    /** A thin horizontal band (centre row 31, sigma 4 px) of patchy fog, colour 197. */
    private static int[][] horizontalFog() {
        Random r = new Random(0x40F06);
        float[][] lat = {lattice(r, 4), lattice(r, 8), lattice(r, 16)};
        int n = 64;
        int[] px = new int[n * n];
        for (int y = 0; y < n; y++) {
            float dy = (y - 31.0f) / 4.0f;
            float band = (float) Math.exp(-0.5 * dy * dy);
            for (int x = 0; x < n; x++) {
                float ends = smooth(0.0f, 0.2f, (x + 0.5f) / n) * smooth(1.0f, 0.8f, (x + 0.5f) / n);
                float f = fbm(r, lat, x / (float) n, y / (float) n * 0.25f);
                float a = 210.0f * band * ends * clamp((f - 0.3f) * 2.4f, 0, 1);
                px[y * n + x] = (int) clamp(a, 0, 210) << 24 | 197 << 16 | 197 << 8 | 197;
            }
        }
        return new int[][]{{n, n}, px};
    }

    /** A stochastic dither disc: opaque white pixels, density 0.2 at the centre falling to 0 at r = 256. */
    private static int[][] fogDithered() {
        Random r = new Random(0xD17E2);
        int n = 512;
        int[] px = new int[n * n];
        for (int y = 0; y < n; y++) {
            for (int x = 0; x < n; x++) {
                double dx = x + 0.5 - 256, dy = y + 0.5 - 256;
                double d = Math.sqrt(dx * dx + dy * dy) / 25.6;
                double density = Math.max(0.0, 0.2 * (1.0 - d / 10.5));
                if (r.nextDouble() < density) px[y * n + x] = 0xFFFFFFFF;
            }
        }
        return new int[][]{{n, n}, px};
    }

    private static float smooth(float e0, float e1, float v) {
        float t = clamp((v - e0) / (e1 - e0), 0, 1);
        return t * t * (3 - 2 * t);
    }

    private static float clamp(float v, float lo, float hi) {
        return v < lo ? lo : (v > hi ? hi : v);
    }
}
